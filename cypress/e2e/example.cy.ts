describe('component library demo smoke journey', () => {
  it('opens the real home page and a core component demo', () => {
    cy.visit('/')
    cy.contains('h1', 'RayTable').should('be.visible')
    cy.contains('button', '查看示範').click()
    cy.contains('h1', '組件目錄').should('be.visible')
    cy.contains('h3', 'SearchableListPanel')
      .parents('.demo-card')
      .contains('button', '查看示範')
      .click()
    cy.contains('h1', 'SearchableListPanel 組件示範').should('be.visible')
    cy.contains('用戶管理').should('be.visible')
  })
})

describe('local mock search and pagination', () => {
  it('uses stable mock identities and real filtered totals, resets page after search/size changes', () => {
    cy.visit('/demo/searchable-list-panel')
    const rows = '#searchable-list-panel-demo .el-table__body-wrapper tbody tr'
    cy.get(rows).should('have.length', 2).first().should('contain', '張小明')
    cy.get('.el-pagination__total').should('contain', '5')
    cy.get('.el-pagination .btn-next').click()
    cy.get(rows).first().should('contain', '王小美')
    cy.get(rows).last().should('contain', '陳大強')
    cy.get('.search-input input').type('林小芳{enter}')
    cy.get(rows).should('have.length', 1).first().should('contain', '林小芳')
    cy.get('.el-pagination__total').should('contain', '1')
    cy.get('.el-pager .is-active')
      .invoke('text')
      .should('match', /^\s*1\s*$/)
    cy.get('.search-input input').clear().type('{enter}')
    cy.get(rows).should('have.length', 2).first().should('contain', '張小明')
    cy.get('.el-pagination .btn-next').click()
    cy.get('.el-pagination .el-select').click()
    cy.get('.el-select-dropdown__item')
      .filter(':visible')
      .contains(/^\s*5\s*項\/頁\s*$/)
      .click()
    cy.get(rows).should('have.length', 5)
    cy.get('.el-pager .is-active')
      .invoke('text')
      .should('match', /^\s*1\s*$/)
    cy.get('.search-input input').type('not-a-user{enter}')
    cy.contains('.el-empty', '暫無資料').should('be.visible')
    cy.get('.el-pagination').should('not.exist')
  })
})

describe('home preview and grouped component discovery', () => {
  it('supports search, pagination, empty recovery and page-size changes on the home page', () => {
    cy.visit('/')
    const rows = '.home-preview .el-table__body-wrapper tbody tr'
    cy.get(rows).should('have.length', 3).first().should('contain', '張小明')
    cy.get('.home-preview .btn-next').click()
    cy.get(rows).should('have.length', 2).first().should('contain', '陳大強')
    cy.get('.home-preview input').first().type('工程部{enter}')
    cy.get(rows).should('have.length', 2).first().should('contain', '張小明')
    cy.get('.home-preview .el-pagination__total').should('contain', '2')
    cy.get('.home-preview input').first().clear().type('不存在的用戶{enter}')
    cy.get('.home-preview .el-empty').should('be.visible')
    cy.get('.home-preview .el-pagination').should('not.exist')
    cy.get('.home-preview input').first().clear().type('{enter}')
    cy.get(rows).should('have.length', 3)
    cy.get('.home-preview .el-pagination .el-select').click()
    cy.get('.el-select-dropdown__item')
      .filter(':visible')
      .contains(/^\s*5\s*項\/頁\s*$/)
      .click()
    cy.get(rows).should('have.length', 5)
  })

  it('keeps all demos reachable in four categories with expandable feature details', () => {
    cy.visit('/demo')
    cy.get('.catalog-nav a').should('have.length', 4)
    cy.get('.catalog-group').should('have.length', 4)
    cy.get('.demo-card').should('have.length', 14)
    cy.get('.catalog-nav a[href="#dialogs"]').click()
    cy.get('#dialogs h2').should('be.visible').and('contain', '對話框')
    cy.get('#dialogs details').first().find('summary').click()
    cy.get('#dialogs details').first().should('have.attr', 'open')
    cy.get('#dialogs details').first().find('li').should('be.visible')
  })
})
